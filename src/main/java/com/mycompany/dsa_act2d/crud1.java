    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String sql = "UPDATE studentdb SET "
            + "[Firstname] = ?, [Middlename] = ?, "
            + "[Surname] = ?, [Address] = ?, [Contact_no] = ? "
            + "WHERE [StudentID] = ?";

        if (txtStudentid.getText().trim().isEmpty()) 
        {
            JOptionPane.showMessageDialog(this,
                "Please enter a Student ID.");
            return;
        }

        String url = "jdbc:ucanaccess://C://Users//Windows//Documents//studentdb.accdb";

        try (Connection conn = DriverManager.getConnection(url);
            PreparedStatement stmt = conn.prepareStatement(sql)) 
        {

            stmt.setString(1, txtFirstname.getText().trim());
            stmt.setString(2, txtMiddlename.getText().trim());
            stmt.setString(3, txtSurname.getText().trim());
            stmt.setString(4, txtAddress.getText().trim());
            stmt.setString(5, txtContact.getText().trim());
            stmt.setString(6, txtStudentid.getText().trim());

            int rows = stmt.executeUpdate();

            if (rows > 0) 
            {
                JOptionPane.showMessageDialog(this,
                    "Student updated successfully!");
                clearFields();
                msAccessDB(jTable1);
            } 
            else 
            {
                JOptionPane.showMessageDialog(this,
                    "Student ID not found.");
            }

        } 
        catch (SQLException ex) 
        {
            JOptionPane.showMessageDialog(this,
                "UPDATE ERROR: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String id = txtStudentid.getText().trim();

        if (id.isEmpty()) 
        {
            JOptionPane.showMessageDialog(this,
                "Please enter a Student ID.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete Student ID " + id + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) 
        {
            return;
        }

        String sql = "DELETE FROM studentdb WHERE [StudentID] = ?";

        try (Connection conn = DriverManager.getConnection(
                "jdbc:ucanaccess://C://Users//Windows//Documents//studentdb.accdb");
            PreparedStatement stmt = conn.prepareStatement(sql)) 
        {

        stmt.setString(1, id);

        int rows = stmt.executeUpdate();

        if (rows > 0) 
        {
            JOptionPane.showMessageDialog(this,
                    "Student deleted successfully!");
            clearFields();
            msAccessDB(jTable1);
        } 
        else 
        {
            JOptionPane.showMessageDialog(this,
                    "Student ID not found.");
        }

        } 
        catch (SQLException ex) 
        {
            JOptionPane.showMessageDialog(this,
                "DELETE ERROR: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

